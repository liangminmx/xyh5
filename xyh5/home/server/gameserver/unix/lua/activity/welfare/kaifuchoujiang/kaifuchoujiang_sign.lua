local nResId = CRESOURCEFLOWACTION.eFt_KaiFuChouJiang_Play_Sign
local nLuaIdActivity = LUARESOURCEFLOWACTION[nResId]

local Kaifuchoujiang_Info_Ins = _kaifuchoujiang_Info['root'][1]['group']
-- Note:
--      data1 group下的id


-- ////////////////////////////////////////////////////////////////////////////////////////////////////////////////
--	玩家登入（只有 ChouJiang_OnLogin 中调用到）
-- ////////////////////////////////////////////////////////////////////////////////////////////////////////////////
function ChouJiang_Sign_OnLogin(_idCharacter,_nOsTimes)
   if   false == System_IsExistTempData(_idCharacter,nLuaIdActivity) then
        System_AddTempData(_idCharacter,nLuaIdActivity)    
   end 
end

-- ////////////////////////////////////////////////////////////////////////////////////////////////////////////////
--	设置 group id
-- ////////////////////////////////////////////////////////////////////////////////////////////////////////////////
function ChouJiang_Sign_SetGroupId(_idCharacter,_nGroupId)
    System_SetTempData(_idCharacter,nLuaIdActivity,1,_nGroupId,false)
end

-- ////////////////////////////////////////////////////////////////////////////////////////////////////////////////
--	获得 group id
-- ////////////////////////////////////////////////////////////////////////////////////////////////////////////////
function ChouJiang_Sign_GetGroupId(_idCharacter)    
    return System_GetTempData(_idCharacter,nLuaIdActivity,1)
end

-- ////////////////////////////////////////////////////////////////////////////////////////////////////////////////
--	设置临时数据，当前时间
-- ////////////////////////////////////////////////////////////////////////////////////////////////////////////////
function ChouJiang_Sign_SetNowTime(_idCharacter,_nTime)
    System_SetTempData(_idCharacter,nLuaIdActivity,2,_nTime,false)
end

-- ////////////////////////////////////////////////////////////////////////////////////////////////////////////////
--	获得临时数据，当前时间
-- ////////////////////////////////////////////////////////////////////////////////////////////////////////////////
function ChouJiang_Sign_GetNowTime(_idCharacter)    
    return System_GetTempData(_idCharacter,nLuaIdActivity,2)
end

-- ////////////////////////////////////////////////////////////////////////////////////////////////////////////////
--	获得奖励次数信息
-- ////////////////////////////////////////////////////////////////////////////////////////////////////////////////
function ChouJiang_Sign_GetRewardTime(_idCharacter)    
    return System_GetTempDataStr(_idCharacter,nLuaIdActivity)
end

-- ////////////////////////////////////////////////////////////////////////////////////////////////////////////////
--	设置奖励次数信息
-- ////////////////////////////////////////////////////////////////////////////////////////////////////////////////
function ChouJiang_Sign_SetRewardTime(_idCharacter,sItemTimes)    
    System_SetTempDataStr(_idCharacter,nLuaIdActivity,sItemTimes,false)
end

-- ////////////////////////////////////////////////////////////////////////////////////////////////////////////////
--  根据当前记录的开启 id ，获得 group 下的key
--  Note：现在所有 serverNum 都是 -1 了
-- ////////////////////////////////////////////////////////////////////////////////////////////////////////////////
function ChouJiang_Sign_GetServerKey(_idCharacter)
    local nNowId = ChouJiang_Sign_GetGroupId(_idCharacter)   
    for k,v in pairs(Kaifuchoujiang_Info_Ins) do
        if  v['id'] == nNowId then
            return k
        end
    end
end