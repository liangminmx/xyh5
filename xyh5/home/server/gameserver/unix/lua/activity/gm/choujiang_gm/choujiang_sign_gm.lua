

-----------------------------------------------------------------------
--  该文件仅仅对应 GM 抽奖的 id
--  这里不做任何逻辑处理，只做记录的存取
-----------------------------------------------------------------------

local nResId = CRESOURCEFLOWACTION.eFt_KaiFuChouJiang_Gm_Sign
local nLuaIdActivity = LUARESOURCEFLOWACTION[nResId]

local Gm_Choujiang_Info_Ins = _kaifuchoujiang_gm_Info['root'][1]['group']
-- Note:
--      data1 group下的id

-- ////////////////////////////////////////////////////////////////////////////////////////////////////////////////
--	玩家登入（只有 GM_ChouJiang_OnLogin 中调用到）
-- ////////////////////////////////////////////////////////////////////////////////////////////////////////////////
function GM_ChouJiang_Sign_OnLogin(_idCharacter)
	--取下背包空间 也可创建背包
	System_GetKaiFuChouJiangBagSpaceNum(_idCharacter)
    if  false == System_IsExistTempData(_idCharacter,nLuaIdActivity) then				
        System_AddTempData(_idCharacter,nLuaIdActivity)
    end
end

-- ////////////////////////////////////////////////////////////////////////////////////////////////////////////////
--	设置 group id
-- ////////////////////////////////////////////////////////////////////////////////////////////////////////////////
function GM_ChouJiang_Sign_SetGroupId(_idCharacter,_nGroupId)
    System_SetTempData(_idCharacter,nLuaIdActivity,1,_nGroupId,false)
end

-- ////////////////////////////////////////////////////////////////////////////////////////////////////////////////
--	获得 group id
-- ////////////////////////////////////////////////////////////////////////////////////////////////////////////////
function GM_ChouJiang_Sign_GetGroupId(_idCharacter) 
    return System_GetTempData(_idCharacter,nLuaIdActivity,1)
end

-- ////////////////////////////////////////////////////////////////////////////////////////////////////////////////
--	设置临时数据，当前时间
-- ////////////////////////////////////////////////////////////////////////////////////////////////////////////////
function GM_ChouJiang_Sign_SetNowTime(_idCharacter,_nTime)
    System_SetTempData(_idCharacter,nLuaIdActivity,2,_nTime,false)
end

-- ////////////////////////////////////////////////////////////////////////////////////////////////////////////////
--	获得临时数据，当前时间
-- ////////////////////////////////////////////////////////////////////////////////////////////////////////////////
function GM_ChouJiang_Sign_GetNowTime(_idCharacter)    
    return System_GetTempData(_idCharacter,nLuaIdActivity,2)
end

-- ////////////////////////////////////////////////////////////////////////////////////////////////////////////////
--	设置临时数据，活动开启时间
-- ////////////////////////////////////////////////////////////////////////////////////////////////////////////////
function GM_ChouJiang_Sign_SetOpenTime(_idCharacter,_nTime)
    System_SetTempData(_idCharacter,nLuaIdActivity,2,_nTime,false)
end

-- ////////////////////////////////////////////////////////////////////////////////////////////////////////////////
--	获得临时数据，活动开启时间
-- ////////////////////////////////////////////////////////////////////////////////////////////////////////////////
function GM_ChouJiang_Sign_GetOpenTime(_idCharacter)    
    return System_GetTempData(_idCharacter,nLuaIdActivity,2)
end

-- ////////////////////////////////////////////////////////////////////////////////////////////////////////////////
--	获得奖励次数信息
-- ////////////////////////////////////////////////////////////////////////////////////////////////////////////////
function GM_ChouJiang_Sign_GetRewardTime(_idCharacter)    
    return System_GetTempDataStr(_idCharacter,nLuaIdActivity)
end

-- ////////////////////////////////////////////////////////////////////////////////////////////////////////////////
--	设置奖励次数信息
-- ////////////////////////////////////////////////////////////////////////////////////////////////////////////////
function GM_ChouJiang_Sign_SetRewardTime(_idCharacter,sItemTimes)    
    System_SetTempDataStr(_idCharacter,nLuaIdActivity,sItemTimes,false)
end

-- ////////////////////////////////////////////////////////////////////////////////////////////////////////////////
--  根据当前记录的开启 id ，获得 group 下的key
--  Note：现在所有 serverNum 都是 -1 了
-- ////////////////////////////////////////////////////////////////////////////////////////////////////////////////
function GM_ChouJiang_Sign_GetServerKey(_idCharacter)
    local nNowId = GM_ChouJiang_Sign_GetGroupId(_idCharacter)   
    for k,v in pairs(Gm_Choujiang_Info_Ins) do
        if  v['id'] == nNowId then
            return k
        end
    end
end